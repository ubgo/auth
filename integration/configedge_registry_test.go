// The builders of the two modules registered here rather than beside the
// others in configedge_test.go, so adding a plugin touches one file. ldap
// gets a directory that knows nobody: the edge test signs in through the
// base plugins, and only needs the ldap plugin to pass auth.New.
func init() {
	edgeBuilders["ldap.Option"] = func(ee *edgeEnv, opts []reflect.Value) ([]auth.Plugin, []auth.Option) {
		nobody := ldap.DirectoryFunc(func(context.Context, string, string) (ldap.Entry, error) {
			return ldap.Entry{}, ldap.ErrInvalidCredentials
		})
		return edgeBase(ee, ldap.New(append([]ldap.Option{ldap.WithDirectory(nobody)}, edgeAs[ldap.Option](opts)...)...)), nil
	}
	edgeBuilders["pow.Option"] = func(ee *edgeEnv, opts []reflect.Value) ([]auth.Plugin, []auth.Option) {
		return edgeBase(ee, pow.New(edgeAs[pow.Option](opts)...)), nil
	}
	edgeBuilders["stale.Option"] = func(ee *edgeEnv, opts []reflect.Value) ([]auth.Plugin, []auth.Option) {
		return edgeBase(ee, stale.New(edgeAs[stale.Option](opts)...)), nil
	}
	edgeBuilders["siwe.Option"] = func(ee *edgeEnv, opts []reflect.Value) ([]auth.Plugin, []auth.Option) {
		return edgeBase(ee, siwe.New(edgeAs[siwe.Option](opts)...)), nil
	}
	// samlidp needs an issuer, a login page, a signing key and one service
	// provider to pass Validate; the edge option comes after them, so it
	// overrides (ServiceProviders appends, so its edge SP is checked too).
	edgeBuilders["samlidp.Option"] = func(ee *edgeEnv, opts []reflect.Value) ([]auth.Plugin, []auth.Option) {
		key, cert := edgeSAMLKey()
		sp := samlidp.ServiceProvider{EntityID: edgeBaseURL + "/sp", ACSURLs: []string{edgeBaseURL + "/sp/acs"}}
		base := []samlidp.Option{samlidp.Issuer(edgeBaseURL), samlidp.LoginPage("/login"), samlidp.SigningKey(key, cert), samlidp.ServiceProviders(sp)}
		return edgeBase(ee, samlidp.New(append(base, edgeAs[samlidp.Option](opts)...)...)), nil
	}
	edgeBuilders["metadata.Option"] = func(ee *edgeEnv, opts []reflect.Value) ([]auth.Plugin, []auth.Option) {
		return edgeBase(ee, metadata.New(edgeAs[metadata.Option](opts)...)), nil
	}
	edgeBuilders["webhook.Option"] = func(ee *edgeEnv, opts []reflect.Value) ([]auth.Plugin, []auth.Option) {
		return edgeBase(ee, webhook.New(edgeAs[webhook.Option](opts)...)), nil
	}
	// orgjwt's options configure a claims func, not a plugin: it is wired
	// as a jwt template's claims beside the organization plugin it reads.
	edgeBuilders["orgjwt.Option"] = func(ee *edgeEnv, opts []reflect.Value) ([]auth.Plugin, []auth.Option) {
		org := organization.New()
		claims, err := orgjwt.Claims(org, edgeAs[orgjwt.Option](opts)...)
		if err != nil {
			// Claims refuses at construction; auth.New is where the edge
			// case looks for the refusal, so carry it there.
			return edgeBase(ee, edgeRefusal{err: err}), nil
		}
		tmpl := jwt.WithTemplate("org", jwt.Template{Claims: claims})
		return edgeBase(ee, org, jwt.New(jwt.WithSigningKey(ee.sig), tmpl)), nil
	}
}

// edgeRefusal is a plugin whose Validate returns an option refusal that a
// constructor (not auth.New) reported, so the edge case sees it at start.
type edgeRefusal struct{ err error }

func (edgeRefusal) Name() string                  { return "edge_refusal" }
func (r edgeRefusal) Validate(*auth.Config) error { return r.err }

// edgeSAMLKey is a self-signed P-256 key pair for the samlidp builder, made
// once per run. Generation failing is a broken test machine, so it panics,
// which the edge case reports.
var edgeSAMLKey = sync.OnceValues(func() (crypto.Signer, *x509.Certificate) {
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		panic(err)
	}
	now := time.Now()
	tmpl := &x509.Certificate{SerialNumber: big.NewInt(1), Subject: pkix.Name{CommonName: "configedge"}, NotBefore: now.Add(-time.Hour), NotAfter: now.Add(24 * time.Hour)}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	if err != nil {
		panic(err)
	}
	cert, err := x509.ParseCertificate(der)
	if err != nil {
		panic(err)
	}
	return key, cert
})
