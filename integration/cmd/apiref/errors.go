package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"

	"github.com/ubgo/auth"
)

// The generated error-code files, by name under the output directory.
const (
	fileErrorCodesMD   = "error-codes.md"
	fileErrorCodesJSON = "error-codes.json"
	fileErrorCodesTS   = "error-codes.ts"
)

// errorCode is one entry of the generated list.
type errorCode struct {
	Code    string `json:"code"`
	Status  int    `json:"status"`
	Message string `json:"message"`
	// Plugin is the owner: the prefix of the code, or "core" for the core's
	// own codes, including the three without a prefix.
	Plugin string `json:"plugin"`
}

// ErrCodeConflict is returned when two declarations share a code with a
// different status or message: the generated list could not say which answer
// a client gets.
var ErrCodeConflict = errors.New("apiref: error code declared twice with different status or message")

// checkConflicts fails on auth.ErrorCodeConflicts, naming the codes.
func checkConflicts() error {
	if c := auth.ErrorCodeConflicts(); len(c) > 0 {
		return fmt.Errorf("%w: %s", ErrCodeConflict, strings.Join(c, ", "))
	}
	return nil
}

// errorCodes is every error the core and the wired plugins declare, sorted
// by code. The list comes from auth.Errors(): the package-level NewError
// declarations of every imported plugin, so a plugin the generator does not
// import is absent, which is why plugins() imports them all.
func errorCodes() []errorCode {
	var out []errorCode
	for _, e := range auth.Errors() {
		plugin := auth.CorePluginName
		if p, _, ok := strings.Cut(e.Code, "."); ok && p != "auth" {
			plugin = p
		}
		out = append(out, errorCode{Code: e.Code, Status: e.Status, Message: e.Message, Plugin: plugin})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Code < out[j].Code })
	return out
}

// renderErrorCodesMD writes the reference table.
func renderErrorCodesMD(codes []errorCode) []byte {
	var b strings.Builder
	b.WriteString("# Error codes\n\n")
	b.WriteString("Every error code the core and the built-in plugins can answer, with its HTTP status and message. This file is generated by `task docs:api` from the errors the packages declare with `auth.NewError`; do not edit it by hand, `task check` fails when it is stale. The same list is [`error-codes.json`](error-codes.json) for tooling and [`error-codes.ts`](error-codes.ts) for a TypeScript frontend. [Errors](../concepts/errors.md) explains when each is returned.\n\n")
	b.WriteString("| Code | Status | Message | Plugin |\n|---|---|---|---|\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "| `%s` | %d | %s | %s |\n", c.Code, c.Status, c.Message, c.Plugin)
	}
	return []byte(b.String())
}

// renderErrorCodesJSON writes the list as JSON, one object per code.
func renderErrorCodesJSON(codes []errorCode) ([]byte, error) {
	b, err := json.MarshalIndent(codes, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

// conceptCode finds the codes the hand-written concepts page documents, as
// `code` cells in its tables.
var conceptCode = regexp.MustCompile("(?m)^\\| `([a-z0-9_.]+)` \\| [0-9]{3} \\|")

// errUndocumented is returned when a declared code has no row on the concepts
// page: the generated list says what the code is, the page says when it is
// returned, and a code without the second half is a frontend mapping nobody
// can write.
var errUndocumented = errors.New("apiref: error code not documented in docs/concepts/errors.md")

// checkDocumented fails when a declared code is missing from the concepts
// page at path, or the page lists a code nothing declares.
func checkDocumented(path string, codes []errorCode) error {
	page, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	documented := map[string]bool{}
	for _, m := range conceptCode.FindAllStringSubmatch(string(page), -1) {
		documented[m[1]] = true
	}
	declared := map[string]bool{}
	for _, c := range codes {
		declared[c.Code] = true
		if !documented[c.Code] {
			return fmt.Errorf("%w: %s", errUndocumented, c.Code)
		}
	}
	for code := range documented {
		if !declared[code] {
			return fmt.Errorf("apiref: docs/concepts/errors.md lists %q, which nothing declares", code)
		}
	}
	return nil
}
